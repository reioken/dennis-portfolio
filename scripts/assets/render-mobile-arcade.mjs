/** Render the real hall models once, for the phone's scrollable exhibition.
 * Run against astro dev (window.__hall is dev-only). Keep captures outside the
 * watched tree, then copy the completed WebPs into public/media/mobile-arcade.
 * node scripts/assets/render-mobile-arcade.mjs OUT [http://localhost:4321]
 */
import { chromium } from 'playwright';
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { outDir } from '../qa/hero/_out.mjs';

const out = outDir(process.argv[2], 'render-mobile-arcade.mjs OUT [BASE]');
const base = process.argv[3] ?? 'http://localhost:4321';
const browser = await chromium.launch({ headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  page.on('pageerror', error => console.error(error));
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => window.__hall?.readyDone && window.__hall.powerAt === null && !window.__hall.lateQueue.length && !window.__hall.lateAttaching, null, { timeout: 120000 });
  const slugs = await page.evaluate(() => window.__hall.machines.map(m => m.item.slug).filter(slug => slug !== 'telefon'));
  for (const slug of slugs) {
    const data = await page.evaluate(async slug => {
      const h = window.__hall;
      h.setFocus(h.machines.findIndex(m => m.item.slug === slug));
      h.start();
      await new Promise(resolve => setTimeout(resolve, 900));
      h.stop();
      const m = h.machines.find(m => m.item.slug === slug);
      h.machines.forEach(other => { other.group.visible = other === m; });
      h.tv.rig.visible = false;
      h.wallPaint.update('', m.group.position.x, true, false, true);
      h.renderer.setPixelRatio(1);
      h.renderer.setSize(780, 940, false);
      h.composer?.setSize(780, 940);
      h.camera.aspect = 780 / 940;
      h.camera.fov = 39;
      const x = m.group.position.x;
      h.camera.position.set(x - 1.25, 1.45, 3.8);
      h.camera.lookAt(x, 1.03, 0);
      h.camera.updateProjectionMatrix();
      h.camera.updateMatrixWorld(true);
      h.scene.updateMatrixWorld(true);
      h.mirrorDirty = true;
      h.renderFrame();
      return h.renderer.domElement.toDataURL('image/png').split(',')[1];
    }, slug);
    await mkdir(out, { recursive: true });
    const input = Buffer.from(data, 'base64');
    await sharp(input).webp({ quality: 85 }).toFile(`${out}/${slug}.webp`);
    await sharp(input).resize(390, 470).webp({ quality: 82 }).toFile(`${out}/${slug}-sm.webp`);
    console.log(`Rendered ${slug}`);
  }
  await writeFile(`${out}/README.txt`, 'Real hall models, 780 × 940 and 390 × 470. Generated by scripts/assets/render-mobile-arcade.mjs.\n');
} finally {
  await browser.close();
}
